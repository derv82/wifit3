#!/usr/bin/env python3
"""Regenerate src/wifit3/chips/rtl8192eu/constants.py from pinned rtl8xxxu headers.

constants.py holds every regs.h / rtl8xxxu.h #define the package references as ``C.<NAME>``
(plus the defines those expand to), kept verbatim with BIT()/GENMASK() preserved. Adapted from
scripts/chips/rtl8192fu/extract_source.py; reused on the RTL8192EU source, not its output.

Usage: extract_constants.py --source <dir with regs.h and rtl8xxxu.h>
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[3] / "src/wifit3/chips/rtl8192eu"
HEADERS = ("rtl8xxxu_regs.h", "rtl8xxxu.h")
_DEFINE = re.compile(r"^#define\s+(\w+)\s+(.+?)\s*(?:/\*.*)?$")
_NAME = re.compile(r"\b[A-Z][A-Z0-9_]+\b")


def _defines(source: Path) -> dict[str, str]:
    found: dict[str, str] = {}
    for header in HEADERS:
        for line in (source / header).read_text().splitlines():
            match = _DEFINE.match(line.strip())
            if match is None or "(" in match.group(1):
                continue
            value = re.sub(r"\b(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", match.group(2))
            found.setdefault(match.group(1), value)
    return found


def write_constants(source: Path, source_tag: str) -> None:
    defines = _defines(source)
    wanted: set[str] = set()
    for path in PACKAGE.glob("*.py"):
        if path.name in ("constants.py", "tables.py"):
            continue
        wanted |= set(re.findall(r"\bC\.([A-Z][A-Z0-9_]+)\b", path.read_text()))
    wanted -= {"BIT", "GENMASK"}
    missing = sorted(name for name in wanted if name not in defines)
    if missing:
        raise SystemExit(f"not #defined in {HEADERS}: {', '.join(missing)}")

    ordered: list[str] = []

    def visit(name: str) -> None:
        if name in ordered:
            return
        for dependency in _NAME.findall(defines[name]):
            if dependency in defines and dependency not in ("BIT", "GENMASK"):
                visit(dependency)
        ordered.append(name)

    for name in sorted(wanted):
        visit(name)
    lines = [
        f"# Generated by scripts/chips/rtl8192eu/extract_constants.py from rtl8xxxu {source_tag} "
        "regs.h + rtl8xxxu.h.\n",
        "\n\n",
        "def BIT(n: int) -> int:\n    return 1 << n\n\n\n",
        "def GENMASK(high: int, low: int) -> int:\n    return ((1 << (high - low + 1)) - 1) << low\n\n\n",
    ]
    for name in ordered:
        lines.append(f"{name} = {defines[name]}\n")
    (PACKAGE / "constants.py").write_text("".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True,
                        help="directory holding regs.h and rtl8xxxu.h")
    parser.add_argument("--tag", default="v6.6", help="source version, for the generated header")
    args = parser.parse_args()
    write_constants(args.source, args.tag)


if __name__ == "__main__":
    main()
