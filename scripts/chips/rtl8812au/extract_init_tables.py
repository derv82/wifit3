"""Extract rtw8812a init tables from kernel C source to Python data files.

Source: driver_sources/rtw88-source-v6.18/rtw8812a_table.c
Output: src/wifit3/chips/rtl8812au/assets/{mac,agc,bb,rf_a,rf_b}_tbl.py

8812A has FIVE tables vs 8821A's four (rf_b is the second RF chain — 8812A
is 2T2R, 8821A is 1T1R). Each table is a flat u32 list; the IF/ELIF/ELSE/
ENDIF bitfield-rfe phy_cond markers are decoded at runtime by the shared
`rtw88_base.phy_cond` walker (chip_id=RTW_CHIP_TYPE_8812A → 88xxA bitfield
rfe semantics, same as 8821A).

We preserve the C order and values 1:1 — no resolution at extract time —
so the data files diff cleanly against future kernel versions.

Usage:
    .venv\\Scripts\\python.exe scripts\\rtl8812au\\extract_init_tables.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "driver_sources/rtw88-source-v6.18/rtw8812a_table.c"
OUT_DIR = ROOT / "src/wifit3/chips/rtl8812au/assets"

TABLES = ("mac", "agc", "bb", "rf_a", "rf_b")


def parse_table(text: str, name: str) -> list[int]:
    """Return the flat u32 list for `static const u32 rtw8812a_<name>[] = { ... };`."""
    pat = re.compile(
        rf"static\s+const\s+u32\s+rtw8812a_{re.escape(name)}\[\]\s*=\s*\{{(.*?)\}}\s*;",
        re.DOTALL,
    )
    m = pat.search(text)
    if not m:
        raise SystemExit(f"rtw8812a_{name} not found in source")
    body = m.group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.DOTALL)
    body = re.sub(r"//.*", "", body)
    return [int(tok, 16) for tok in re.findall(r"0[xX][0-9A-Fa-f]+", body)]


def count_markers(words: list[int]) -> dict[str, int]:
    """Walk tile-by-tile, classify each tile, sanity-check balance."""
    counts = {"cfg": 0, "if": 0, "elif": 0, "else": 0, "endif": 0, "neg": 0}
    i = 0
    n = len(words)
    while i + 1 < n:
        w0 = words[i]
        pos = (w0 >> 31) & 1
        neg = (w0 >> 30) & 1
        if pos:
            branch = (w0 >> 28) & 3
            counts[("if", "elif", "else", "endif")[branch]] += 1
        elif neg:
            counts["neg"] += 1
        else:
            counts["cfg"] += 1
        i += 2
    return counts


