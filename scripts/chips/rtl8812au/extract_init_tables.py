def emit(name: str, words: list[int]) -> Path:
    counts = count_markers(words)
    summary = (
        f"cfg={counts['cfg']}  IF={counts['if']}  ELIF={counts['elif']}  "
        f"ELSE={counts['else']}  ENDIF={counts['endif']}  neg={counts['neg']}  "
        f"u32s={len(words)}"
    )
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"{name}_tbl.py"
    lines = [HEADER_TMPL.format(name=name, summary=summary)]
    for k in range(0, len(words), 2):
        a, b = words[k], words[k + 1]
        lines.append(f"    0x{a:08X}, 0x{b:08X},\n")
    lines.append("]\n")
    out.write_text("".join(lines), encoding="utf-8")
    print(f"  {name:5s} -> {out.relative_to(ROOT)}  ({summary})")

    if counts["if"] + counts["elif"] != counts["neg"]:
        print(f"    WARN: IF+ELIF ({counts['if']+counts['elif']}) != neg ({counts['neg']})")
    if counts["if"] != counts["endif"]:
        print(f"    WARN: IF ({counts['if']}) != ENDIF ({counts['endif']})")
    return out


def main() -> int:
    if not SRC.exists():
        print(f"ERROR: missing {SRC}", file=sys.stderr)
        return 1
    text = SRC.read_text(encoding="utf-8", errors="replace")
    print(f"Reading {SRC.relative_to(ROOT)}")
    for name in TABLES:
        words = parse_table(text, name)
        emit(name, words)
    return 0


if __name__ == "__main__":
    sys.exit(main())
