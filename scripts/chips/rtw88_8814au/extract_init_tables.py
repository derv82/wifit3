"""Extract rtw8814a init tables from kernel C source to Python data files.

Source: driver_sources/rtw88-source-v6.18/rtw8814a_table.c
Output: src/wifit3/chips/rtw88_8814au/assets/{mac,agc,bb,rf_a,rf_b,rf_c,rf_d}_tbl.py

Seven tables are arrays of u32 in C, walked 2 at a time by the rtw88 phy_cond
runtime (see :mod:`wifit3.chips.rtw88_base.phy_cond`). The 8814a is 4T4R, so it
has four RF radio tables (A/B/C/D) vs the 8822b's two.

Usage:
    .venv/Scripts/python.exe scripts/chips/rtw88_8814au/extract_init_tables.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "driver_sources/rtw88-source-v6.18/rtw8814a_table.c"
OUT_DIR = ROOT / "src/wifit3/chips/rtw88_8814au/assets"

TABLES = ("mac", "agc", "bb", "rf_a", "rf_b", "rf_c", "rf_d")


def parse_table(text: str, name: str) -> list[int]:
    """Return the flat u32 list for `static const u32 rtw8814a_<name>[] = { ... };`."""
    pat = re.compile(
        rf"static\s+const\s+u32\s+rtw8814a_{re.escape(name)}\[\]\s*=\s*\{{(.*?)\}}\s*;",
        re.DOTALL,
    )
    m = pat.search(text)
    if not m:
        raise SystemExit(f"rtw8814a_{name} not found in source")
    body = m.group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.DOTALL)
    body = re.sub(r"//.*", "", body)
    return [int(tok, 16) for tok in re.findall(r"0[xX][0-9A-Fa-f]+", body)]


def count_markers(words: list[int]) -> dict[str, int]:
    counts = {"cfg": 0, "if": 0, "elif": 0, "else": 0, "endif": 0, "neg": 0}
    i, n = 0, len(words)
    while i + 1 < n:
        w0 = words[i]
        pos = (w0 >> 31) & 1
        neg = (w0 >> 30) & 1
        if pos:
            branch = (w0 >> 28) & 3
            counts[("if", "elif", "else", "endif")[branch]] += 1
        elif neg:
            counts["neg"] += 1
        else:
            counts["cfg"] += 1
        i += 2
    return counts


