"""Regenerate rtl8192fu tables.py + constants.py from the pinned rtl8xxxu source.

constants.py holds every regs.h / rtl8xxxu.h #define the package references as ``C.<NAME>``
(plus the defines those expand to), pasted verbatim with BIT()/GENMASK() kept.
"""
from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SOURCE = REPO / "driver_sources/rtl8xxxu-source-v6.19.14"
PACKAGE = REPO / "src/wifit3/chips/rtl8192fu"
TABLES = (
    ("rtl8192f_mac_init_table", 4, 2),
    ("rtl8192fu_phy_init_table", 4, 8),
    ("rtl8192f_agc_table", 4, 8),
    ("rtl8192fu_radioa_init_table", 2, 8),
    ("rtl8192fu_radiob_init_table", 2, 8),
)
HEADERS = ("regs.h", "rtl8xxxu.h")
_DEFINE = re.compile(r"^#define\s+(\w+)\s+(.+?)\s*(?:/\*.*)?$")
_NAME = re.compile(r"\b[A-Z][A-Z0-9_]+\b")


def extract_table(source: str, name: str) -> list[tuple[int, int]]:
    match = re.search(rf"{name}\[\]\s*=\s*\{{(.*?)\n\}};", source, re.DOTALL)
    if match is None:
        raise RuntimeError(f"table not found: {name}")
    pairs = re.findall(r"\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}", match.group(1))
    return [(int(register, 16), int(value, 16)) for register, value in pairs]


def write_tables() -> None:
    source = (SOURCE / "8192f.c").read_text()
    lines = ["# Generated by scripts/chips/rtl8192fu/extract_source.py from rtl8xxxu v6.19.14 8192f.c.\n"]
    for name, register_digits, value_digits in TABLES:
        lines.append(f"\n{name.upper()} = (\n")
        for register, value in extract_table(source, name):
            lines.append(f"    (0x{register:0{register_digits}x}, 0x{value:0{value_digits}x}),\n")
        lines.append(")\n")
    (PACKAGE / "tables.py").write_text("".join(lines))


def _defines() -> dict[str, str]:
    found: dict[str, str] = {}
    for header in HEADERS:
        lines = (SOURCE / header).read_text().splitlines()
        for line in lines:
            match = _DEFINE.match(line.strip())
            if match is None or "(" in match.group(1):
                continue
            value = re.sub(r"\b(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", match.group(2))
            found.setdefault(match.group(1), value)
    return found


def write_constants() -> None:
    defines = _defines()
    wanted: set[str] = set()
    for path in PACKAGE.glob("*.py"):
        if path.name in ("constants.py", "tables.py"):
            continue
        wanted |= set(re.findall(r"\bC\.([A-Z][A-Z0-9_]+)\b", path.read_text()))
    wanted -= {"BIT", "GENMASK"}
    missing = sorted(name for name in wanted if name not in defines)
    if missing:
        raise SystemExit(f"not #defined in {HEADERS}: {', '.join(missing)}")

    ordered: list[str] = []

    def visit(name: str) -> None:
        if name in ordered:
            return
        for dependency in _NAME.findall(defines[name]):
            if dependency in defines and dependency not in ("BIT", "GENMASK"):
                visit(dependency)
        ordered.append(name)

    for name in sorted(wanted):
        visit(name)
    lines = [
        "# Generated by scripts/chips/rtl8192fu/extract_source.py from rtl8xxxu v6.19.14 regs.h + rtl8xxxu.h.\n",
        "\n\n",
        "def BIT(n: int) -> int:\n    return 1 << n\n\n\n",
        "def GENMASK(high: int, low: int) -> int:\n    return ((1 << (high - low + 1)) - 1) << low\n\n\n",
    ]
    for name in ordered:
        lines.append(f"{name} = {defines[name]}\n")
    (PACKAGE / "constants.py").write_text("".join(lines))


if __name__ == "__main__":
    write_tables()
    write_constants()
