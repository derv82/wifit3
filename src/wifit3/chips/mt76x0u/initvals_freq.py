def find_freq_item(channel: int, use_sdm: bool) -> FreqItem | None:
    """Find the freq_item for `channel` in the appropriate plan.

    Mirrors the kernel's `for (i = 0; i < ARRAY_SIZE(...); i++)` linear search.
    Returns None if the channel isn't in the plan.
    """
    plan = SDM_FREQUENCY_PLAN if use_sdm else FREQUENCY_PLAN
    for item in plan:
        if item.channel == channel:
            return item
    return None
