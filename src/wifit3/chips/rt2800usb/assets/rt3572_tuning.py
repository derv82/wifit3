def get_sequence(channel):
    ch_key = int(channel)
    if ch_key not in CHANNELS:
        return None
    
    base = list(BASE_5G) if 'BASE_5G' in globals() and ch_key >= 36 else list(BASE_2G)
    
    for pos, idx, val in CHANNELS[ch_key]:
        if pos < len(base):
            base[pos] = (idx, val)
        else:
            base.append((idx, val))
            
    return base
